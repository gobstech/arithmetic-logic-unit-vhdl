LIBRARY ieee;
USE ieee.std_logic_1164.all;
USE work.compadder_package.all;
USE work.prodcomp_package.all;
USE work.Comparator_Signals.all;

ENTITY Circ_Comp IS
	PORT( SW : IN STD_LOGIC_VECTOR(10 DOWNTO 0);
			HEX6 : OUT STD_LOGIC_VECTOR(0 TO 6);
			HEX4 : OUT STD_LOGIC_VECTOR(0 TO 6);
			HEX2 : OUT STD_LOGIC_VECTOR(0 TO 6);
			HEX0 : OUT STD_LOGIC_VECTOR(0 TO 6);
			LEDR : OUT STD_LOGIC_VECTOR(5 DOWNTO 0));
END Circ_Comp;

ARCHITECTURE Final OF Circ_Comp IS 
	SIGNAL A : STD_LOGIC_VECTOR(3 DOWNTO 0);
	SIGNAL B : STD_LOGIC_VECTOR(3 DOWNTO 0);
	SIGNAL C : STD_LOGIC_VECTOR(1 DOWNTO 0);
	SIGNAL D : STD_LOGIC_VECTOR(1 DOWNTO 0);
	SIGNAL C1 : STD_LOGIC;
	SIGNAL C2 : STD_LOGIC;
	SIGNAL C3 : STD_LOGIC;
	SIGNAL Cout : STD_LOGIC;
	SIGNAL Cin : STD_LOGIC;
	SIGNAL Cin2 : STD_LOGIC;
	SIGNAL Overflow : STD_LOGIC;
	SIGNAL Opcode : STD_LOGIC_VECTOR(2 DOWNTO 0);
	SIGNAL HEX2_SOMA : STD_LOGIC_VECTOR(0 TO 6);
	SIGNAL HEX4_SOMA : STD_LOGIC_VECTOR(0 TO 6);
	SIGNAL HEX2_SUB : STD_LOGIC_VECTOR(0 TO 6);
	SIGNAL HEX4_SUB : STD_LOGIC_VECTOR(0 TO 6);
	SIGNAL HEX2_PROD : STD_LOGIC_VECTOR(0 TO 6);
	SIGNAL HEX4_PROD : STD_LOGIC_VECTOR(0 TO 6);
	SIGNAL HEX2_COMP : STD_LOGIC_VECTOR(0 TO 6);
	SIGNAL HEX4_COMP : STD_LOGIC_VECTOR(0 TO 6);
	SIGNAL Res1 : STD_LOGIC_VECTOR(0 TO 6);
	SIGNAL Res2 : STD_LOGIC_VECTOR(0 TO 6);
	SIGNAL Res3 : STD_LOGIC_VECTOR(0 TO 6);
	SIGNAL Equ : STD_LOGIC;
	SIGNAL Grt : STD_LOGIC;
	SIGNAL Lst : STD_LOGIC;
	SIGNAL Operator_Vector : STD_LOGIC_VECTOR(2 DOWNTO 0);
	SIGNAL Operation1 : STD_LOGIC_VECTOR(3 DOWNTO 0);
	SIGNAL Operation2 : STD_LOGIC_VECTOR(3 DOWNTO 0);
	SIGNAL Operation3 : STD_LOGIC_VECTOR(3 DOWNTO 0);
	SIGNAL HEX6_aux1 : STD_LOGIC_VECTOR(0 TO 6);
	SIGNAL HEX6_aux2 : STD_LOGIC_VECTOR(0 TO 6);
	SIGNAL HEX6_aux3 : STD_LOGIC_VECTOR(0 TO 6);
	SIGNAL Flag_Vector1 : STD_LOGIC_VECTOR(2 DOWNTO 0);
	SIGNAL Flag_Vector2 : STD_LOGIC_VECTOR(2 DOWNTO 0);
	SIGNAL Flag_Vector3 : STD_LOGIC_VECTOR(2 DOWNTO 0);
	SIGNAL Operation1_aux : STD_LOGIC_VECTOR(
	SIGNAL Zero : STD_LOGIC;
BEGIN
	A <= SW(10 DOWNTO 7);
	B <= SW(6 DOWNTO 3);
	C <= SW(8 DOWNTO 7);
	D <= SW(4 DOWNTO 3);
	Opcode <= SW(2 DOWNTO 0);
	
	Operation1 <= A AND B;
	Operation2 <= A OR B;
	Operation3 <= NOT B;
	
	Operation4: adder_comp PORT MAP (Cin,A,B,C1,HEX2_SOMA,HEX4_SOMA,Res1);
	Operation5: adder_comp PORT MAP (Cin2,A,B,C2,HEX2_SUB,HEX4_SUB,Res2);
	Operation6: Prod_Comp PORT MAP (C,D,C3,HEX2_PROD,HEX4_PROD,Res3);
	Operation7: Comparator_Operations PORT MAP (A,B,Equ,Grt,Lst,HEX2_COMP,HEX4_COMP);
	
	Operator_Vector <= Equ&Grt&Lst;
	
	WITH Opcode SELECT
	  Overflow <= C1 XOR (B(2) AND A(2)) WHEN "100",
	              C2 XOR (B(2) AND A(2)) WHEN "101",
					  '0' WHEN OTHERS;
	
	WITH Opcode SELECT
	  Cout <= C1 WHEN "100",
	          C2 WHEN "101",
				 C3 WHEN "110",
				 '0' WHEN OTHERS;
	
	WITH Opcode SELECT 
	  Zero <= Res_g1 WHEN "101"
	
	Flag_Vector <= Overflow&Zero&Cout;
	
	
	WITH Operation1 SELECT
	   HEX6_aux1 <= "0000001" WHEN "0000",
					"1001111" WHEN "0001",
					"0010010" WHEN "0010",
					"0000110" WHEN "0011",
					"1001100" WHEN "0100",
					"0100100" WHEN "0101",
					"0100000" WHEN "0110",
					"0001111" WHEN "0111",
					"0000000" WHEN OTHERS;
					
	WITH Operation2 SELECT
	   HEX6_aux2 <= "0000001" WHEN "0000",
					"1001111" WHEN "0001",
					"0010010" WHEN "0010",
					"0000110" WHEN "0011",
					"1001100" WHEN "0100",
					"0100100" WHEN "0101",
					"0100000" WHEN "0110",
					"0001111" WHEN "0111",
					"0000000" WHEN OTHERS;
					
	WITH Operation3 SELECT
	   HEX6_aux3 <= "0000001" WHEN "0000",
					"1001111" WHEN "0001",
					"0010010" WHEN "0010",
					"0000110" WHEN "0011",
					"1001100" WHEN "0100",
					"0100100" WHEN "0101",
					"0100000" WHEN "0110",
					"0001111" WHEN "0111",
					"0000000" WHEN OTHERS;
	
	WITH Opcode SELECT
		HEX6 <= "1111111" WHEN "000",
		        HEX6_aux1 WHEN "001",
				  HEX6_aux2 WHEN "010",
				  HEX6_aux3 WHEN "011",
				  Res1 WHEN "100",
				  Res2 WHEN "110",
		        Res3 WHEN "111",
			"0000000" WHEN OTHERS;
			
	WITH Opcode SELECT 
		LEDR(5 DOWNTO 3) <= Operator_Vector WHEN "111",
		                    "000"WHEN OTHERS; 	
								  
	WITH Opcode SELECT
	   LEDR(2 DOWNTO 0) <= "000" WHEN "000",
							     Flag_Vector WHEN OTHERS;
END Final;	